import numpy as np
import pandas as pd
from sklearn.model_selection import KFold
from sklearn.linear_model import LinearRegression
from sklearn.metrics import r2_score, mean_absolute_error, mean_squared_error

# ---------- 1. Data ----------
df = pd.read_csv('PRABASI.csv')
cols_to_keep = [
    'Year', 'Sex', 'Source (x)', 'Destination (y)', 'Distance',
    'Total_Male_x', 'Total_Female_x', 'Total_Male_y', 'Total_Female_y', 'Migrants']
df = df[cols_to_keep]

sex_selected = "Female"
df = df[df["Sex"] == sex_selected]
df = df.drop(columns=['Sex'])
df = df[df["Source (x)"] != df["Destination (y)"]]
df = df.dropna().reset_index(drop=True)
target = "Migrants"
id_cols = ["Source (x)", "Destination (y)"]


USE_ID_COLS = False

# ---------- 2. Feature engineering ----------
def add_features(frame):
    out = frame.copy()
    if "Distance" in out.columns:
        out["log_Distance"] = np.log1p(out["Distance"])
    for c in [c for c in frame.columns if c.endswith("_x") and c not in id_cols]:
        c_y = c[:-2] + "_y"
        if c_y in frame.columns:
            out[f"{c[:-2]}_ratio"] = (frame[c_y] + 1e-6) / (frame[c] + 1e-6)
    return out

# ---------- 3. Temporal holdout ----------
year_held = 1991

train_mask = df["Year"] != year_held
test_mask = df["Year"] == year_held
train_years = sorted(df.loc[train_mask, "Year"].unique())

excluded = [target, "Year"] + ([] if USE_ID_COLS else id_cols)
feature_cols = [c for c in df.columns if c not in excluded]
X_all = add_features(df[feature_cols])
if not USE_ID_COLS:
    pass

X_train, X_test = X_all[train_mask].reset_index(drop=True), X_all[test_mask].reset_index(drop=True)
y_train, y_test = df.loc[train_mask, target].reset_index(drop=True), df.loc[test_mask, target].reset_index(drop=True)
y_train_log, y_test_log = np.log1p(y_train), np.log1p(y_test)

print(f"Train rows: {len(X_train)} (years {train_years})")
print(f"Test rows:  {len(X_test)} (year {year_held})")

# ---------- 4. Model: ordinary least squares ----------
models = {"OLS": LinearRegression()}

LOG_LO, LOG_HI = y_train_log.min(), y_train_log.max()

def predict_log(model, X_):
    return np.clip(model.predict(X_), LOG_LO, LOG_HI)

def metrics(y_log_true, y_log_pred, y_raw_true):
    y_raw_pred = np.clip(np.expm1(y_log_pred), 0, None)      # back to migrant counts
    return {
        "R2_log": r2_score(y_log_true, y_log_pred),
        "RMSE_log": np.sqrt(mean_squared_error(y_log_true, y_log_pred)),
        "R2_raw": r2_score(y_raw_true, y_raw_pred),
        "MAE_raw": mean_absolute_error(y_raw_true, y_raw_pred),
        "RMSE_raw": np.sqrt(mean_squared_error(y_raw_true, y_raw_pred)),
    }, y_raw_pred

# ---------- 5. K-fold CV on the TRAINING data only ----------
kf = KFold(n_splits=5, shuffle=True, random_state=42)

def cross_validate(model, X_, y_log_, y_raw_):
    oof_log = np.zeros(len(y_log_))
    fold_r2 = []
    for tr, va in kf.split(X_):
        model.fit(X_.iloc[tr], y_log_.iloc[tr])
        oof_log[va] = predict_log(model, X_.iloc[va])
        fold_r2.append(r2_score(y_log_.iloc[va], oof_log[va]))
    m, _ = metrics(y_log_, oof_log, y_raw_)
    m["R2_log_fold_mean"], m["R2_log_fold_std"] = np.mean(fold_r2), np.std(fold_r2)
    return m

cv_results = {name: cross_validate(m, X_train, y_train_log, y_train) for name, m in models.items()}
cv_df = pd.DataFrame(cv_results).T
cv_df.index.name = "Model"
print(f"\n=== 5-fold CV on training years {train_years} ===")
print(cv_df.to_string())

# ---------- 6. Final evaluation on the held-out year ----------
test_results, test_preds, fitted = {}, {}, {}
for name, m in models.items():
    m.fit(X_train, y_train_log)
    fitted[name] = m
    test_results[name], test_preds[name] = metrics(y_test_log, predict_log(m, X_test), y_test)

test_df = pd.DataFrame(test_results).T
test_df.index.name = "Model"
print(f"\n=== Temporal holdout: test on {year_held} ===")
print(test_df.to_string())

ols = fitted["OLS"]

# ---------- 7. Coefficients (OLS equivalent of feature importance) ----------
coef_df = pd.DataFrame({
    "Coefficient": ols.coef_,
    "Std_Coefficient": ols.coef_ * X_train.std().values,   # effect of a 1-std change on log(migrants)
}, index=X_train.columns)
coef_df.loc["Intercept"] = [ols.intercept_, np.nan]
coef_df = coef_df.reindex(coef_df["Std_Coefficient"].abs().sort_values(ascending=False, na_position="last").index)
print("\nCoefficients:\n", coef_df)

# ---------- 8. Save results to CSV ----------
cv_df.to_csv(f"cv_results_train_excl_{year_held}.csv")
test_df.to_csv(f"test_results_{year_held}.csv")

pred_df = df.loc[test_mask, id_cols + [target]].reset_index(drop=True)
pred_df = pred_df.rename(columns={target: "Actual_Migrants"})
pred_df["Pred_OLS"] = np.round(test_preds["OLS"]).astype(int)
pred_df["Abs_Error"] = (pred_df["Actual_Migrants"] - pred_df["Pred_OLS"]).abs()
pred_df.to_csv(f"predictions_{year_held}_vs_actual.csv", index=False)

