"""
Straight-line (haversine) distance between Indian states, using proper
polygon centroids (not just averaged lat/lon points).

METHOD
------
1. Load a GeoJSON of Indian state boundaries (ST_NM = state name field).
   Source used here: a widely-used community GeoJSON of Indian states
   https://gist.githubusercontent.com/jbrobst/56c13bbbf9d97d187fea01ca62ea5112/raw/e388c4cae20aa53cb5090210a42ebb9b765c0a36/india_states.geojson
2. Re-project the polygons to an equal-area CRS before computing centroids.
   (Computing a centroid directly in lat/lon (EPSG:4326) distorts the result
   because degrees of longitude shrink toward the poles -- for a country
   the size of India this can shift a centroid by tens of km. Projecting to
   an equal-area CRS first, e.g. EPSG:3857-avoid / better: India-specific
   Lambert Azimuthal Equal Area, gives a geometrically correct centroid.)
3. Convert the centroid back to lat/lon (EPSG:4326).
4. Compute the great-circle (haversine) distance between any two states'
   centroids.
5. Save the distance between each state/union territory pair as a csv file

"""

import sys
import math
import argparse
import geopandas as gpd
import pandas as pd

GEOJSON_URL = (
    "https://gist.githubusercontent.com/jbrobst/56c13bbbf9d97d187fea01ca62ea5112/"
    "raw/e388c4cae20aa53cb5090210a42ebb9b765c0a36/india_states.geojson"
)

# Using an equal-area CRS avoids distortion when calculating centroids from polygons spanning many degrees of latitude.
INDIA_EQUAL_AREA_CRS = "+proj=laea +lat_0=22.9734 +lon_0=78.6569 +units=m +ellps=WGS84"


def load_state_centroids(geojson_source: str = GEOJSON_URL) -> pd.DataFrame:
    """Load state polygons and return accurate centroid lat/lon per state."""
    gdf = gpd.read_file(geojson_source)

    # Normalise a couple of naming inconsistencies seen in this dataset
    gdf.loc[gdf["ST_NM"].isin(["Ladakh", "Jammu & Kashmir"]), "ST_NM"] = "Jammu and Kashmir"

    # Project to equal-area CRS -> compute centroid -> project back to lat/lon
    projected = gdf.to_crs(INDIA_EQUAL_AREA_CRS)
    centroids_proj = projected.geometry.centroid
    centroids_latlon = gpd.GeoSeries(centroids_proj, crs=INDIA_EQUAL_AREA_CRS).to_crs(epsg=4326)

    out = pd.DataFrame({
        "state": gdf["ST_NM"],
        "lat": centroids_latlon.y,
        "lon": centroids_latlon.x,
    })
    # Some datasets split a state into multiple polygon rows (islands etc.);
    # dissolve by state first for a single, correct centroid per state.
    dissolved = gdf.dissolve(by="ST_NM")
    dissolved_proj = dissolved.to_crs(INDIA_EQUAL_AREA_CRS)
    dissolved_centroids = gpd.GeoSeries(dissolved_proj.geometry.centroid, crs=INDIA_EQUAL_AREA_CRS).to_crs(epsg=4326)
    out = pd.DataFrame({
        "state": dissolved.index,
        "lat": dissolved_centroids.y.values,
        "lon": dissolved_centroids.x.values,
    })
    return out.sort_values("state").reset_index(drop=True)


def haversine_km(lat1, lon1, lat2, lon2) -> float:
    """Great-circle distance between two lat/lon points, in km."""
    R = 6371.0088  # mean Earth radius, km
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dphi = math.radians(lat2 - lat1)
    dlambda = math.radians(lon2 - lon1)
    a = math.sin(dphi / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dlambda / 2) ** 2
    return 2 * R * math.asin(math.sqrt(a))


def distance_between(df: pd.DataFrame, state_a: str, state_b: str) -> float:
    row_a = df.loc[df["state"].str.lower() == state_a.lower()]
    row_b = df.loc[df["state"].str.lower() == state_b.lower()]
    if row_a.empty or row_b.empty:
        available = ", ".join(df["state"].tolist())
        raise ValueError(f"State not found. Available: {available}")
    a, b = row_a.iloc[0], row_b.iloc[0]
    return haversine_km(a.lat, a.lon, b.lat, b.lon)


def build_full_matrix(df: pd.DataFrame) -> pd.DataFrame:
    states = df["state"].tolist()
    coords = list(zip(df["lat"], df["lon"]))
    matrix = pd.DataFrame(index=states, columns=states, dtype=float)
    for i, s1 in enumerate(states):
        for j, s2 in enumerate(states):
            matrix.loc[s1, s2] = haversine_km(*coords[i], *coords[j])
    return matrix


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("state_a", nargs="?")
    parser.add_argument("state_b", nargs="?")
    parser.add_argument("--matrix", action="store_true", help="Compute full pairwise distance matrix")
    parser.add_argument("--geojson", default=GEOJSON_URL, help="Path or URL to states GeoJSON")
    parser.add_argument("--save-centroids", default=None, help="Optional path to save centroid CSV")
    args, _unknown = parser.parse_known_args()

    df = load_state_centroids(args.geojson)

    if args.save_centroids:
        df.to_csv(args.save_centroids, index=False)
        print(f"Saved centroids to {args.save_centroids}")

    if args.matrix:
        matrix = build_full_matrix(df)
        matrix.to_csv("state_distance_matrix.csv")
        print("Saved full distance matrix to state_distance_matrix.csv")
    elif args.state_a and args.state_b:
        d = distance_between(df, args.state_a, args.state_b)
        print(f"{args.state_a} <-> {args.state_b}: {d:.1f} km")
    else:
        print(df.to_string(index=False))

# Load centroids
df = load_state_centroids()

# Convert the wide distance matrix into a long-format list:
# source, destination, distance
matrix = build_full_matrix(df)
long_format = matrix.stack().reset_index()
long_format.columns = ["source", "destination", "distance_km"]

# Save as CSV
long_format.to_csv("state_distance_list.csv", index=False)
print("Saved state_distance_list.csv")