# OLS reads every column as a magnitude, so state ID codes (e.g. 9, 27) would be treated as
# numbers where 27 > 9, which has no meaning. For a spatial holdout this matters even more,
# since the test destination codes are never seen in training. Keep False.
USE_ID_COLS = False

# ---------- 2. Feature engineering ----------
def add_features(frame):
    out = frame.copy()
    if "Distance" in out.columns:
        out["log_Distance"] = np.log1p(out["Distance"])
    for c in [c for c in frame.columns if c.endswith("_x") and c not in id_cols]:
        c_y = c[:-2] + "_y"
        if c_y in frame.columns:
            out[f"{c[:-2]}_ratio"] = (frame[c_y] + 1e-6) / (frame[c] + 1e-6)
    return out

# ---------- 3. Spatial holdout: 20% of destination codes = test ----------
test_frac = 0.20
split_seed = 42

all_dest = np.sort(df[dst_col].unique())            # State codes 1...35
rng = np.random.RandomState(split_seed)
