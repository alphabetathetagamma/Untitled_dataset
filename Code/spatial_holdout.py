# ---------- 5. 5-fold CV on TRAINING destinations only (grouped by destination) ----------
# Each fold holds out whole destinations, mirroring the spatial test setup.
gkf = GroupKFold(n_splits=5)

def cross_validate(model, X_, y_log_, y_raw_, groups_):
    oof_log = np.zeros(len(y_log_))
    fold_r2 = []
    for tr, va in gkf.split(X_, y_log_, groups=groups_):
        model.fit(X_.iloc[tr], y_log_.iloc[tr])
        oof_log[va] = predict_log(model, X_.iloc[va])
        fold_r2.append(r2_score(y_log_.iloc[va], oof_log[va]))
    m, _ = metrics(y_log_, oof_log, y_raw_)
    m["R2_log_fold_mean"], m["R2_log_fold_std"] = np.mean(fold_r2), np.std(fold_r2)
    return m

cv_results = {name: cross_validate(m, X_train, y_train_log, y_train, groups_train)
              for name, m in models.items()}
