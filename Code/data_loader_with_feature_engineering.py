import numpy as np
import pandas as pd

# ---------- 1. Data ----------
df = pd.read_csv('PRABASI.csv')

# ---------- 2. Select sex: Male/Female ----------

sex_selected="Female"                                  #Select specific sex for study
df = df[df["Sex"] == sex_selected]
df = df[df["Source (x)"] != df["Destination (y)"]]     #ensure no self-loops
df = df.dropna().reset_index(drop=True)
target = "Migrants"
id_cols = ["Source (x)", "Destination (y)"]


# ---------- 3. Feature engineering ----------
# a. Skewed positive features (distance, populations, etc.) perform better in log space.
#    Source/Destination are state IDs, so they are used as identifiers, not as magnitudes.
# b. Ratio features between destination and source (pull vs. push)

def add_features(frame):
    out = frame.copy()
    if "Distance" in out.columns:
        out["log_Distance"] = np.log1p(out["Distance"])
    for c in [c for c in frame.columns if c.endswith("_x")]:
        c_y = c[:-2] + "_y"
        if c_y in frame.columns:
            out[f"{c[:-2]}_ratio"] = (frame[c_y] + 1e-6) / (frame[c] + 1e-6)
    return out



feature_cols = [c for c in df.columns if c not in [target, "Year"]]   # Year is not a feature
X_all = add_features(df[feature_cols])